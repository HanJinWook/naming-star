/// 성씨명 → 한자 후보 목록 (등록 순서 유지)
Map<String, List<SurnameEntry>> get surnamesByName {
  final map = <String, List<SurnameEntry>>{};
  final order = <String>[];
  for (final e in surnameDb) {
    if (!map.containsKey(e.name)) {
      map[e.name] = [];
      order.add(e.name);
    }
    map[e.name]!.add(e);
  }
  return {for (final k in order) k: map[k]!};
}

/// 성씨 검색 (이름 또는 한자로)
List<String> searchSurnameNames(String query) {
  final q = query.trim();
  final names = surnamesByName.keys.toList();
  if (q.isEmpty) return names;
  return names.where((n) {
    if (n.contains(q)) return true;
    return surnamesByName[n]!.any((e) => e.hanja.contains(q));
  }).toList();
}
